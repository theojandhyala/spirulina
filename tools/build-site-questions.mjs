/**
 * Generates the question cards on the website's main page from the production
 * manual, so the front page and the manual cannot drift apart.
 *
 *   node tools/build-site-questions.mjs
 *
 * Reads every chapter heading in BB-OPS-001 and the paragraph beneath it, and
 * rewrites whatever sits between the QUESTIONS:START and QUESTIONS:END markers
 * in site/index.html. Each card deep-links to that chapter in the manual.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { marked } from "marked";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "docs/BB-OPS-001_Spirulina-Production-Manual.md");
const SITE = join(ROOT, "site/index.html");

// must match the id scheme in build-docs-viewer.mjs
const slug = (s) =>
  s.toLowerCase().replace(/[^\w\s-]/g, "").trim().replace(/\s+/g, "-").slice(0, 50);

const esc = (s) =>
  String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");

const tokens = marked.lexer(readFileSync(SRC, "utf8"));

const chapters = [];
let seenTitle = false;
let cur = null;
for (const t of tokens) {
  if (t.type === "heading" && t.depth === 1) {
    if (!seenTitle) { seenTitle = true; continue; }   // document title
    cur = { title: t.text.trim(), blurb: "", first: null };
    chapters.push(cur);
    continue;
  }
  if (!cur) continue;
  if (t.type === "heading" && t.depth === 2 && !cur.first) {
    cur.first = "ops-" + slug(t.text);
    continue;
  }
  if (t.type === "paragraph" && !cur.first && !cur.blurb) {
    cur.blurb = t.text.replace(/[*_`]/g, "").replace(/\s+/g, " ").trim();
  }
}

if (!chapters.length) throw new Error("build-site-questions: no chapters found");
const bad = chapters.filter((c) => !c.first || !c.blurb);
if (bad.length) {
  throw new Error(
    "build-site-questions: chapter missing a description or first section: " +
      bad.map((c) => c.title).join(", ")
  );
}

const cards = chapters
  .map(
    (c) =>
      '        <a class="qcard" href="manual/#' + c.first + '">\n' +
      "          <h3>" + esc(c.title) + "</h3>\n" +
      "          <p>" + esc(c.blurb) + "</p>\n" +
      '          <span class="qcard-go">Read this chapter →</span>\n' +
      "        </a>"
  )
  .join("\n");

const block =
  "<!-- QUESTIONS:START — generated by tools/build-site-questions.mjs, do not edit by hand -->\n" +
  '      <div class="qcards">\n' + cards + "\n      </div>\n" +
  "      <!-- QUESTIONS:END -->";

let html = readFileSync(SITE, "utf8");
const re = /<!-- QUESTIONS:START[\s\S]*?<!-- QUESTIONS:END -->/;
if (!re.test(html)) throw new Error("build-site-questions: markers not found in site/index.html");
html = html.replace(re, block);
writeFileSync(SITE, html);

console.log("wrote " + chapters.length + " question cards into site/index.html");
for (const c of chapters) console.log("  " + c.title + "  →  manual/#" + c.first);
